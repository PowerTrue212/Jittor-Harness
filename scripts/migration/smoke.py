"""Real CPU framework smoke for ordinary preparation, frozen delivery and negative control.

Run setup, then recheck in a new container with the same /work mount. This uses a
known small port; it does not measure autonomous migration of an unfamiliar repo.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from scripts.migrate import finalize  # noqa: E402
from scripts.migration.preparation import baseline, check  # noqa: E402
from scripts.migration.workspace import initialize, read, write  # noqa: E402

SOURCE = '''from torch import nn
from torch.nn import functional as F

class TinyNet(nn.Module):
    def __init__(self):
        super().__init__()
        self.fc1 = nn.Linear(8, 16)
        self.fc2 = nn.Linear(16, 4)

    def forward(self, value):
        return F.softmax(self.fc2(F.relu(self.fc1(value))), dim=-1)
'''
TARGET = '''from jittor import nn

class TinyNet(nn.Module):
    def __init__(self):
        super().__init__()
        self.fc1 = nn.Linear(8, 16)
        self.fc2 = nn.Linear(16, 4)

    def execute(self, value):
        return nn.softmax(self.fc2(nn.relu(self.fc1(value))), dim=-1)
'''


def setup(root: Path) -> None:
    if root.exists():
        raise FileExistsError(root)
    root.mkdir(parents=True)
    upstream = root / "upstream"
    upstream.mkdir()
    (upstream / "main.py").write_text(SOURCE, encoding="utf-8")
    (upstream / "config.json").write_text('{"width": 8}', encoding="utf-8")
    workspace = root / "workspace"
    initialize(workspace, str(upstream), None)
    (workspace / "candidate/main.py").write_text(TARGET, encoding="utf-8")
    task = read(workspace / "task.json")
    task["inputs"] = [{"shape": [2, 8], "dtype": "float32"}]
    for side in ("source", "target"):
        task[side].update(entry="main.py", model="TinyNet", device="cpu")
    task["protocol"]["timeout"] = 600
    write(workspace / "task.json", task)
    write(workspace / "scope.json", {
        "purpose": "CPU two-layer MLP pipeline smoke",
        "public_entries": ["main.TinyNet"],
        "preprocessing": "seeded float32 [2,8] inputs generated by Harness",
        "outputs": "four-class softmax probabilities",
        "state_and_mode": "eval; source state supplied to target by oracle",
        "acceptance_basis": "known equivalent fixture; +1 output negative control",
        "limitations": ["not autonomous migration", "no training or GPU coverage"],
        "assets": [], "environment_files": [
            "/opt/harness/scripts/migration/Dockerfile",
            "/opt/harness/scripts/migration/Smoke.Dockerfile",
        ],
    })
    exercise(root)


def exercise(root: Path) -> None:
    """Resume a failed preparation without discarding its cold-compile evidence."""
    workspace = root / "workspace"
    if not (workspace / "prepared.json").exists():
        task = read(workspace / "task.json")
        task["target"]["env"] = {
            "JITTOR_HOME": str(workspace / "probe-cache/target/jittor")
        }
        write(workspace / "task.json", task)
        baseline(workspace)
    check(workspace)
    positive = finalize(workspace, root / "positive")
    if not positive["passed"]:
        raise RuntimeError(f"positive control failed: {positive['verify']['summary']}")
    (workspace / "candidate/main.py").write_text(
        TARGET.replace("return nn.softmax", "return 1 + nn.softmax"), encoding="utf-8"
    )
    negative = finalize(workspace, root / "negative")
    if negative["passed"]:
        raise RuntimeError("negative control unexpectedly passed")
    write(root / "smoke-result.json", {
        "positive_passed": True, "negative_rejected": True,
        "negative_failure_code": negative["verify"]["failure_code"],
        "recheck_in_new_container": "pending",
    })


def recheck(root: Path) -> None:
    from jittor_harness.contracts import load_task
    from jittor_harness.verification import verify

    check(root / "workspace")
    report = verify(load_task(root / "positive/task.json"), root / "fresh-evidence",
                    trial="fresh-container")
    if not report["passed"]:
        raise RuntimeError(f"fresh container verification failed: {report['summary']}")
    result = read(root / "smoke-result.json")
    result["recheck_in_new_container"] = "passed"
    write(root / "smoke-result.json", result)
    print(result)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("stage", choices=("setup", "resume", "recheck"))
    parser.add_argument("workspace", type=Path)
    args = parser.parse_args()
    {"setup": setup, "resume": exercise, "recheck": recheck}[args.stage](args.workspace.resolve())
